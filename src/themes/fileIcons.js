export function getFileIcon(filename) {
  const lower = filename.toLowerCase()

  if (FILE_NAME_MAP[filename]) return FILE_NAME_MAP[filename]
  if (FILE_NAME_MAP[lower]) return FILE_NAME_MAP[lower]

  const ext = '.' + lower.split('.').pop()
  if (FILE_ICON_MAP[ext]) return FILE_ICON_MAP[ext]

  for (const [key, icon] of Object.entries(FILE_ICON_MAP)) {
    if (lower.endsWith(key)) return icon
  }

  return 'default'
}

export function getFolderIcon(foldername) {
  const lower = foldername.toLowerCase()
  return FOLDER_ICON_MAP[lower] || 'default'
}
